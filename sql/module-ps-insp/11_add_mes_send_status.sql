-- ============================================================
-- module-ps-insp: MES 전송 상태 컬럼 추가
-- 적용 대상: 운영 DB (기존 테이블에 컬럼만 추가)
-- ============================================================
-- 
-- 값: '전송 성공' / '전송 실패' / NULL(미전송)
-- 검사 결과 저장 후 MES 전송 시 자동 업데이트
-- ============================================================

ALTER TABLE ps_inspection
    ADD COLUMN IF NOT EXISTS MES_SEND_STATUS VARCHAR(50) NULL
    COMMENT 'MES 전송 상태 (전송 성공/전송 실패/미전송)'
    AFTER STATUS;
