           SUBSTRING_INDEX(SUBSTRING_INDEX(row_key, '|', 2), '|', -1) AS section,
           SUBSTRING_INDEX(SUBSTRING_INDEX(row_key, '|', 3), '|', -1) AS row_id,
           SUBSTRING_INDEX(row_key, '|', -1) AS kind,
           TRIM(COALESCE(cell_value, '')) AS raw,
           REPLACE(TRIM(COALESCE(cell_value, '')), ',', '') AS v
    FROM steam_cell_value
    WHERE table_name = 'fluidized_detail_main'
      AND month REGEXP '^[0-9]{4}-[0-9]{2}$'
      AND row_key REGEXP '^custom\\|[^|]+\\|[^|]+\\|[^|]+$'
) x
GROUP BY month, section, row_id
